package reporters

import (
	"fmt"
	"sort"
	"strings"
	"time"

	"github.com/theterminalguy/pipedact/pkg/core"
)

// GenerateMarkdownDossier produces the statutory PIPEDA or SOC 2 Type II Self-Assessment Compliance Dossier in Markdown.
func GenerateMarkdownDossier(result *core.AuditResult) string {
	if result.Framework == core.FrameworkSOC2 {
		return generateSOC2MarkdownDossier(result)
	}

	var sb strings.Builder

	sb.WriteString("# OPC PIPEDA Schedule 1 Self-Assessment Compliance Dossier\n")
	sb.WriteString("Generated by: **pipedact v1.2.0**\n")
	sb.WriteString(fmt.Sprintf("Date: %s\n", time.Now().Format("2006-01-02")))
	sb.WriteString("Jurisdiction: **Federal Canada (PIPEDA / Bill C-27 Alignment)**\n\n")

	sb.WriteString("## Executive Summary\n")
	sb.WriteString(fmt.Sprintf("- **Overall Compliance Score:** %d%%\n", result.ComplianceScore))
	sb.WriteString(fmt.Sprintf("- **Readiness Status:** %s\n", result.ScoreLabel))
	sb.WriteString(fmt.Sprintf("- **Files Scanned:** %d (%d lines)\n", result.ScannedFiles, result.ScannedLines))
	sb.WriteString(fmt.Sprintf("- **Active Code Violations:** %d\n\n", len(result.Violations)))

	sb.WriteString("## 10 Fair Information Principles Audit Breakdown\n")

	var principleIDs []int
	for id := range result.PrincipleStatus {
		principleIDs = append(principleIDs, id)
	}
	sort.Ints(principleIDs)

	for _, id := range principleIDs {
		status := result.PrincipleStatus[id]
		p := status.Principle

		statusLabel := "PASS / COMPLIANT"
		if !status.Passing {
			statusLabel = "ACTION REQUIRED (Non-Compliant)"
		}

		verificationMode := "Automated AST & Static Analysis"
		if !p.Automated {
			verificationMode = "Organizational Policy & Endpoint Verification"
		}

		sb.WriteString(fmt.Sprintf("### %s\n", p.Name))
		sb.WriteString(fmt.Sprintf("- **Statutory Citation:** %s\n", p.Statutory))
		sb.WriteString(fmt.Sprintf("- **Statutory Scope:** %s\n", p.Meaning))
		sb.WriteString(fmt.Sprintf("- **Verification Mode:** %s (Weight: %d%%)\n", verificationMode, p.Weight))
		sb.WriteString(fmt.Sprintf("- **Compliance Status:** **%s**\n", statusLabel))
		if len(status.Violations) > 0 {
			sb.WriteString(fmt.Sprintf("- **Active Violations Found:** %d\n", len(status.Violations)))
		} else {
			sb.WriteString(fmt.Sprintf("- **Notes:** %s\n", p.DefaultNote))
		}
		sb.WriteString("\n")
	}

	sb.WriteString("## Code Findings & Remediations\n")
	if len(result.Violations) == 0 {
		sb.WriteString("No active source code violations detected. All statutory gates passed.\n")
	} else {
		for i, v := range result.Violations {
			sb.WriteString(fmt.Sprintf("#### Finding %d: %s\n", i+1, v.RuleID))
			sb.WriteString(fmt.Sprintf("- **Principle:** %s\n", v.Principle))
			sb.WriteString(fmt.Sprintf("- **Severity:** `%s`\n", v.Severity))
			sb.WriteString(fmt.Sprintf("- **Location:** `%s:%d`\n", v.FilePath, v.Line))
			sb.WriteString(fmt.Sprintf("- **Violation Details:** %s\n", v.Message))
			if len(v.FrameworkMappings) > 0 {
				var fwList []string
				for fw, ref := range v.FrameworkMappings {
					fwList = append(fwList, fmt.Sprintf("%s: `%s`", strings.ToUpper(string(fw)), ref))
				}
				sb.WriteString(fmt.Sprintf("- **Cross-Framework References:** %s\n", strings.Join(fwList, " | ")))
			}
			if v.LineText != "" {
				sb.WriteString(fmt.Sprintf("- **Code Snippet:**\n  ```text\n  > %s\n  ```\n", v.LineText))
			}
			sb.WriteString(fmt.Sprintf("- **Statutory Remediation:** %s\n\n", v.Remediation))
		}
	}

	sb.WriteString("---\n")
	sb.WriteString("*Report certified by pipedact — Open Source Canadian Privacy Engineering Initiative.*\n")

	return sb.String()
}

func generateSOC2MarkdownDossier(result *core.AuditResult) string {
	var sb strings.Builder

	sb.WriteString("# AICPA SOC 2 Type II Trust Services Criteria Readiness Dossier\n")
	sb.WriteString("Generated by: **pipedact v1.2.0**\n")
	sb.WriteString(fmt.Sprintf("Date: %s\n", time.Now().Format("2006-01-02")))
	sb.WriteString("Audit Scope: **Security (Common Criteria CC6/CC7) & Privacy Trust Services Criteria (P1-P5)**\n\n")

	sb.WriteString("## Executive Summary\n")
	sb.WriteString(fmt.Sprintf("- **Trust Services Readiness Score:** %d%%\n", result.ComplianceScore))
	sb.WriteString(fmt.Sprintf("- **Auditor Readiness Status:** %s\n", result.ScoreLabel))
	sb.WriteString(fmt.Sprintf("- **Files Scanned:** %d (%d lines)\n", result.ScannedFiles, result.ScannedLines))
	sb.WriteString(fmt.Sprintf("- **Active Control Exceptions:** %d\n\n", len(result.Violations)))

	sb.WriteString("## Trust Services Criteria Breakdown\n\n")
	sb.WriteString("| Criteria ID | Category | Name | Weight | Status | Exceptions |\n")
	sb.WriteString("|---|---|---|---|---|---|\n")

	for _, c := range core.GetSOC2Criteria() {
		status := result.SOC2Status[c.ID]
		statusStr := "✔ PASS"
		excCount := 0
		if status != nil && !status.Passing {
			statusStr = "⚠️ EXCEPTION"
			excCount = len(status.Violations)
		}
		sb.WriteString(fmt.Sprintf("| **%s** | %s | %s | %d%% | **%s** | %d |\n",
			c.ID, c.Category, c.Name, c.Weight, statusStr, excCount))
	}
	sb.WriteString("\n")

	sb.WriteString("## Control Exceptions & Remediations\n")
	if len(result.Violations) == 0 {
		sb.WriteString("No active control exceptions detected. System satisfies automated Trust Services testing criteria.\n")
	} else {
		for i, v := range result.Violations {
			sb.WriteString(fmt.Sprintf("#### Exception %d: %s\n", i+1, v.RuleID))
			sb.WriteString(fmt.Sprintf("- **Control Principle:** %s\n", v.Principle))
			sb.WriteString(fmt.Sprintf("- **Risk Severity:** `%s`\n", v.Severity))
			sb.WriteString(fmt.Sprintf("- **Artifact Location:** `%s:%d`\n", v.FilePath, v.Line))
			sb.WriteString(fmt.Sprintf("- **Deficiency Description:** %s\n", v.Message))
			if len(v.FrameworkMappings) > 0 {
				var fwList []string
				for fw, ref := range v.FrameworkMappings {
					fwList = append(fwList, fmt.Sprintf("%s: `%s`", strings.ToUpper(string(fw)), ref))
				}
				sb.WriteString(fmt.Sprintf("- **Cross-Standard Mappings:** %s\n", strings.Join(fwList, " | ")))
			}
			if v.LineText != "" {
				sb.WriteString(fmt.Sprintf("- **Source Code Snippet:**\n  ```text\n  > %s\n  ```\n", v.LineText))
			}
			sb.WriteString(fmt.Sprintf("- **Remediation Action:** %s\n\n", v.Remediation))
		}
	}

	sb.WriteString("---\n")
	sb.WriteString("*Evidence package generated by pipedact — Continuous Compliance for SOC 2 Type II & PIPEDA.*\n")

	return sb.String()
}
